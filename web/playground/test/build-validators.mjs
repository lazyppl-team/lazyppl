// Generates ../validators.js from protocol.schema.json with Ajv's standalone mode.
//   node build-validators.mjs           write ../validators.js
//   node build-validators.mjs --check   exit 1 if ../validators.js differs from the schema
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MODELS = ['poisson', 'regression', 'piecewise', 'gp', 'wiener', 'clustering', 'irm', 'program', 'ibp', 'graph', 'mondrian'];
const schemaUrl = new URL('protocol.schema.json', import.meta.url);
export const validatorsUrl = new URL('../validators.js', import.meta.url);

export function generate() {
  const schema = JSON.parse(readFileSync(schemaUrl, 'utf8'));
  const ajv = new Ajv({ schemas: [schema], inlineRefs: false, code: { source: true, esm: true } });
  const code = standaloneCode(ajv, Object.fromEntries(MODELS.map(model => [model, `${schema.$id}#/$defs/${model}`])));
  // The page loads validators.js as it is, with no bundler, so the module must not import Ajv's runtime helpers.
  if (/\brequire\(|\bimport\b/.test(code)) {
    throw new Error('The generated validators import a helper; remove the schema keyword that needs it.');
  }
  const { version } = createRequire(import.meta.url)('ajv/package.json');
  return `// Generated by test/build-validators.mjs from test/protocol.schema.json with Ajv ${version}. Do not edit.\n${code}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const generated = generate();
  if (process.argv.includes('--check')) {
    if (readFileSync(validatorsUrl, 'utf8') !== generated) {
      console.error('validators.js is out of date: run `npm run validators` in web/playground/test.');
      process.exit(1);
    }
  } else {
    writeFileSync(validatorsUrl, generated);
  }
}
